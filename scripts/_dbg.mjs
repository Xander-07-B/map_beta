import * as Core from '../js/core/index.js';
import { readFileSync } from 'node:fs';
const fetchJson = async (url) => JSON.parse(readFileSync(url, 'utf8'));
const loaded = await Core.loadScenario('1936', { fetchJson });
const camp = new Core.Campaign(loaded, { seed: 1 });
camp.newGame();
const s = camp.state;
console.log('alliances:', JSON.stringify(s.alliances));
console.log('GER faction:', Core.factionOf(s, 'GER'), 'leader:', Core.factionLeader(s, 'axis'));
const cands = Object.keys(s.countries).filter(t => t !== 'GER' && !Core.factionOf(s, t) && t !== 'POL' && t !== 'FRA');
console.log('candidates:', cands.length, cands.slice(0,5).join(','));
const t = cands[0];
console.log('relations:', JSON.stringify(s.countries.GER.relations));
console.log('invite:', JSON.stringify(Core.validateCommand({ t:'inviteFaction', from:'GER', faction:'axis', to:t }, s, camp.ctx())));
console.log('exec:', JSON.stringify(camp.command({ t:'inviteFaction', from:'GER', faction:'axis', to:t })));
console.log('invites:', JSON.stringify(s.factionInvites));
